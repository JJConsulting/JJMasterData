using System.CodeDom.Compiler;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Threading;
using Microsoft.CodeAnalysis.CSharp;

namespace JJMasterData.Data.SourceGenerators;

internal static class DataAccessSourceEmitter
{
    internal static string Emit(DataAccessModelInfo dataAccessModel, CancellationToken cancellationToken)
    {
        cancellationToken.ThrowIfCancellationRequested();
        using var text = new StringWriter(CultureInfo.InvariantCulture);
        text.NewLine = "\n";
        using var writer = new IndentedTextWriter(text, "    ");
        writer.NewLine = "\n";
        writer.WriteLine("// <auto-generated/>");
        writer.WriteLine("#nullable enable");
        writer.WriteLine();
        writer.WriteLine("using Data = global::JJMasterData.Commons.Data;");
        writer.WriteLine("using Db = global::System.Data.Common;");
        writer.WriteLine("using System = global::System;");
        writer.WriteLine();

        if (dataAccessModel.Namespace.Length != 0)
            OpenBlock(writer, "namespace " + dataAccessModel.Namespace);
        foreach (var container in dataAccessModel.Containers)
            OpenBlock(writer, container);

        var contract = "Data::IDataAccessModel<" + dataAccessModel.TypeName + ">";
        OpenBlock(writer, dataAccessModel.Accessibility + (dataAccessModel.IsRecord ? " partial record class @" : " partial class @") +
                          dataAccessModel.Name + " : " + contract);
        var hasIgnoredRequired = dataAccessModel.Properties.Any(p => p.ReaderMethod == "Ignore");
        if (hasIgnoredRequired)
            WriteConstruction(writer, dataAccessModel);
        WriteResolveOrdinals(writer, dataAccessModel, contract, cancellationToken);
        writer.WriteLine();
        WriteRead(writer, dataAccessModel, contract, hasIgnoredRequired, cancellationToken);
        if (dataAccessModel.Properties.Any(p => p.ReaderMethod == "Model"))
        {
            writer.WriteLine();
            WriteNestedModelHelpers(writer);
        }
        CloseBlock(writer);
        foreach (var _ in dataAccessModel.Containers)
            CloseBlock(writer);
        if (dataAccessModel.Namespace.Length != 0)
            CloseBlock(writer);
        return text.ToString();
    }

    private static void WriteConstruction(IndentedTextWriter writer, DataAccessModelInfo dataAccessModel)
    {
        // Preserve the implicit constructor when adding the SetsRequiredMembers overload.
        if (dataAccessModel.HasImplicitConstructor)
            writer.WriteLine(dataAccessModel.Accessibility + " @" + dataAccessModel.Name + "() { }");
        writer.WriteLine("private readonly struct __DataAccessConstruction { }");
        writer.WriteLine("#pragma warning disable CS8618 // Ignored required members retain their constructor defaults.");
        writer.WriteLine("[global::System.Diagnostics.CodeAnalysis.SetsRequiredMembers]");
        writer.WriteLine("private @" + dataAccessModel.Name + "(__DataAccessConstruction _) : this() { }");
        writer.WriteLine("#pragma warning restore CS8618");
        writer.WriteLine();
    }

    private static void WriteResolveOrdinals(IndentedTextWriter writer, DataAccessModelInfo dataAccessModel, string contract,
        CancellationToken cancellationToken)
    {
        OpenBlock(writer, "static int[] " + contract + ".ResolveOrdinals(Db::DbDataReader reader)");
        writer.WriteLine("var ordinals = new global::System.Collections.Generic.List<int>();");
        foreach (var property in dataAccessModel.Properties)
        {
            cancellationToken.ThrowIfCancellationRequested();
            if (property.ReaderMethod == "Ignore")
                continue;
            writer.WriteLine(property.ReaderMethod == "Model"
                ? "AppendModelOrdinals<" + property.TypeName + ">(reader, ordinals);"
                : "ordinals.Add(Data::DataAccessValueReader.FindOrdinal(reader, " + Literal(property.Column) + "));");
        }
        writer.WriteLine("return ordinals.ToArray();");
        CloseBlock(writer);
    }

    private static void WriteRead(IndentedTextWriter writer, DataAccessModelInfo dataAccessModel, string contract,
        bool hasIgnoredRequired, CancellationToken cancellationToken)
    {
        OpenBlock(writer, "static " + dataAccessModel.TypeName + " " + contract +
                          ".Read(Db::DbDataReader reader, System::ReadOnlySpan<int> ordinals)");
        writer.WriteLine("var item = new " + dataAccessModel.TypeName +
                         (hasIgnoredRequired ? "(default(__DataAccessConstruction));" : "();"));
        if (dataAccessModel.Properties.Any(p => p.ReaderMethod != "Ignore"))
            writer.WriteLine("var index = 0;");
        foreach (var property in dataAccessModel.Properties)
        {
            cancellationToken.ThrowIfCancellationRequested();
            if (property.ReaderMethod == "Ignore")
                continue;
            writer.WriteLine();
            if (property.ReaderMethod == "Model")
            {
                writer.WriteLine("var length_" + property.Name + " = ordinals[index++];");
                writer.WriteLine("item.@" + property.Name + " = ReadModel<" + property.TypeName +
                                 ">(reader, ordinals.Slice(index, length_" + property.Name + "));");
                writer.WriteLine("index += length_" + property.Name + ";");
            }
            else
            {
                OpenBlock(writer);
                writer.WriteLine("var ordinal = ordinals[index++];");
                WritePropertyMapping(writer, property);
                CloseBlock(writer);
            }
        }
        writer.WriteLine();
        writer.WriteLine("return item;");
        CloseBlock(writer);
    }

    private static void WritePropertyMapping(IndentedTextWriter writer, PropertyData property)
    {
        var target = "item.@" + property.Name;
        var nullAssignment = property.Nullable
            ? target + " = null;"
            : "throw Data::DataAccessValueReader.NullValue(" +
              Literal(property.Column) + ", " + Literal(property.DisplayType) + ");";
        var enumCast = property.TypeName.Length == 0 ? "" : "(" + property.TypeName + ")";

        OpenBlock(writer, "if (ordinal >= 0)");
        writer.WriteLine("if (reader.IsDBNull(ordinal))");
        writer.Indent++;
        writer.WriteLine(nullAssignment);
        writer.Indent--;
        writer.WriteLine("else");
        writer.Indent++;
        writer.WriteLine(target + " = " + enumCast + "Data::DataAccessValueReader.Read" +
                         property.ReaderMethod + "(reader, ordinal);");
        writer.Indent--;
        CloseBlock(writer);
    }

    private static void WriteNestedModelHelpers(IndentedTextWriter writer)
    {
        writer.WriteLine("private static void AppendModelOrdinals<T>(Db::DbDataReader reader,");
        writer.WriteLine("    global::System.Collections.Generic.List<int> ordinals)");
        writer.WriteLine("    where T : class, Data::IDataAccessModel<T>");
        OpenBlock(writer);
        writer.WriteLine("var nested = T.ResolveOrdinals(reader);");
        writer.WriteLine("ordinals.Add(nested.Length);");
        writer.WriteLine("ordinals.AddRange(nested);");
        CloseBlock(writer);
        writer.WriteLine();
        writer.WriteLine("private static T ReadModel<T>(Db::DbDataReader reader, System::ReadOnlySpan<int> ordinals)");
        writer.WriteLine("    where T : class, Data::IDataAccessModel<T>");
        writer.WriteLine("    => T.Read(reader, ordinals);");
    }

    private static void OpenBlock(IndentedTextWriter writer, string? declaration = null)
    {
        if (declaration != null)
            writer.WriteLine(declaration);
        writer.WriteLine("{");
        writer.Indent++;
    }

    private static void CloseBlock(IndentedTextWriter writer)
    {
        writer.Indent--;
        writer.WriteLine("}");
    }

    private static string Literal(string text) => SymbolDisplay.FormatLiteral(text, true);
}
